"""Generate .importlinter contracts enforcing module boundaries (DECISIONS D-005).

For every business module X, no other module may import anything of X except X.services and
X.schemas (every other submodule and subpackage is listed as forbidden). `core` is the shared
kernel and is exempt.
Run: python scripts/gen_importlinter.py  (CI checks the file is up to date).
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = sorted(
    p.name
    for p in (ROOT / "corridor").iterdir()
    if p.is_dir() and (p / "apps.py").exists() and p.name != "core"
)
PUBLIC = {"services", "schemas", "__init__"}


def private_submodules(module: str) -> list[str]:
    base = ROOT / "corridor" / module
    names = {p.stem for p in base.glob("*.py")} | {
        p.name for p in base.iterdir() if (p / "__init__.py").exists()
    }
    return sorted(names - PUBLIC)


lines = [
    "# GENERATED by scripts/gen_importlinter.py — do not edit by hand.",
    "[importlinter]",
    "root_package = corridor",
    "include_external_packages = False",
    "",
]
for m in MODULES:
    others = [o for o in MODULES if o != m] + ["core"]
    lines += [
        f"[importlinter:contract:{m}-private]",
        f"name = Only {m}.services / {m}.schemas are public",
        "type = forbidden",
        "source_modules =",
        *[f"    corridor.{o}" for o in others],
        "forbidden_modules =",
        *[f"    corridor.{m}.{p}" for p in private_submodules(m)],
        "allow_indirect_imports = True",
        "",
    ]
(ROOT / ".importlinter").write_text("\n".join(lines), encoding="utf-8")
