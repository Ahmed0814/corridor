"""Generate .importlinter contracts enforcing module boundaries (DECISIONS D-005).

For every business module X, no other module may import X.models, X.api or X.tasks.
Only X.services and X.schemas are public. `core` is the shared kernel and is exempt.
Run: python scripts/gen_importlinter.py  (CI checks the file is up to date).
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = sorted(
    p.name
    for p in (ROOT / "corridor").iterdir()
    if p.is_dir() and (p / "apps.py").exists() and p.name != "core"
)
PRIVATE = ("models", "api", "tasks")

lines = [
    "# GENERATED by scripts/gen_importlinter.py — do not edit by hand.",
    "[importlinter]",
    "root_package = corridor",
    "include_external_packages = False",
    "",
]
for m in MODULES:
    others = [o for o in MODULES if o != m] + ["core"]
    lines += [
        f"[importlinter:contract:{m}-private]",
        f"name = Only {m}.services / {m}.schemas are public",
        "type = forbidden",
        "source_modules =",
        *[f"    corridor.{o}" for o in others],
        "forbidden_modules =",
        *[f"    corridor.{m}.{p}" for p in PRIVATE],
        "allow_indirect_imports = True",
        "",
    ]
(ROOT / ".importlinter").write_text("\n".join(lines), encoding="utf-8")
